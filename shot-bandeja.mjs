import { chromium } from "playwright";
import fs from "node:fs";
const base=process.env.BASE_URL, shots="/tmp/shots";
const cookie=process.env.SESSION_COOKIE;
const browser=await chromium.launch();
const ck=cookie.split("=");
const d=await browser.newContext({viewport:{width:1440,height:900}});
await d.addCookies([{name:ck[0],value:ck.slice(1).join("="),domain:new URL(base).hostname,path:"/",secure:true,httpOnly:true,sameSite:"Lax"}]);
const dp=await d.newPage();
await dp.goto(base+"/chats",{waitUntil:"networkidle"}).catch(()=>{});
await dp.waitForTimeout(3500);
await dp.screenshot({path:shots+"/3-bandeja-desktop.png"});
await dp.click(".room").catch(()=>{});
await dp.waitForTimeout(3500);
await dp.screenshot({path:shots+"/4-conversacion-desktop.png"});
await d.close();
const m=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:2,isMobile:true,hasTouch:true});
await m.addCookies([{name:ck[0],value:ck.slice(1).join("="),domain:new URL(base).hostname,path:"/",secure:true,httpOnly:true,sameSite:"Lax"}]);
const mp=await m.newPage();
await mp.goto(base+"/chats",{waitUntil:"networkidle"}).catch(()=>{});
await mp.waitForTimeout(3500);
await mp.screenshot({path:shots+"/6-bandeja-movil.png"});
await mp.click(".room").catch(()=>{});
await mp.waitForTimeout(3500);
await mp.screenshot({path:shots+"/7-conversacion-movil.png"});
await m.close();
await browser.close();
