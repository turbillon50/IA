import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { openStore, addUser, startChat } from '../server.mjs';

test('dos personas: autenticación, entrega en vivo, historial, permisos y reinicio', async t => {
  const dir=mkdtempSync(join(tmpdir(),'iaapp-chat-'));
  const dbPath=join(dir,'chat.sqlite');
  const seed=openStore(dbPath);
  addUser(seed,'alice','test-alice-password-123','Alicia');
  addUser(seed,'bob','test-bob-password-123','Bob');
  addUser(seed,'eve','test-eve-password-123','Intrusa');
  seed.close();
  let service=await startChat({dbPath,port:0});
  let origin='http://127.0.0.1:'+service.address.port;
  t.after(async()=>{await service.stop();rmSync(dir,{recursive:true,force:true});});
  const call=async(cookie,path,data,method='GET')=>{
    const r=await fetch(origin+path,{method,headers:{...(cookie?{Cookie:cookie}:{}),...(method==='POST'?{'Content-Type':'application/json',Origin:origin}:{})},...(method==='POST'?{body:JSON.stringify(data)}:{})});
    return {status:r.status,data:await r.json(),cookie:r.headers.get('set-cookie')};
  };
  const login=async(username,password)=>{
    const result=await call(null,'/api/login',{username,password},'POST');
    assert.equal(result.status,200);
    return result.cookie.split(';')[0];
  };
  assert.equal((await call(null,'/api/rooms')).status,401);
  assert.equal((await call(null,'/api/login',{username:'alice',password:'incorrecto'},'POST')).status,401);
  const a=await login('alice','test-alice-password-123');
  const b=await login('bob','test-bob-password-123');
  const e=await login('eve','test-eve-password-123');
  const room=(await call(a,'/api/rooms',{kind:'direct',peer:'bob'},'POST'));
  assert.equal(room.status,201);
  const id=room.data.roomId;
  assert.equal((await call(b,'/api/rooms')).data.items[0].id,id);
  assert.equal((await call(a,'/api/rooms',{kind:'direct',peer:'bob'},'POST')).data.roomId,id);
  assert.equal((await call(e,'/api/rooms/'+id+'/messages')).status,404);
  assert.equal((await call(e,'/api/search?q=secreto')).data.items.length,0);
  const stream=await fetch(origin+'/api/events',{headers:{Cookie:b}});
  assert.equal(stream.status,200);
  const reader=stream.body.getReader();
  const first=await reader.read();assert.match(new TextDecoder().decode(first.value),/event: ready/);
  const key='envio-alice-0001';
  const send=await call(a,'/api/rooms/'+id+'/messages',{body:'Secreto real entre personas',key},'POST');
  assert.equal(send.status,201);
  assert.equal(send.data.message.body,'Secreto real entre personas');
  const event=await Promise.race([reader.read(),new Promise((_,reject)=>setTimeout(()=>reject(Error('SSE no recibido')),2000))]);
  assert.match(new TextDecoder().decode(event.value),/event: message/);
  const again=await call(a,'/api/rooms/'+id+'/messages',{body:'Secreto real entre personas',key},'POST');
  assert.equal(again.status,200);assert.equal(again.data.duplicate,true);
  assert.equal((await call(a,'/api/rooms/'+id+'/messages',{body:'Otro cuerpo',key},'POST')).status,409);
  const inbox=(await call(b,'/api/rooms/'+id+'/messages')).data.items;
  assert.equal(inbox.length,1);assert.equal(inbox[0].senderName,'Alicia');
  const reply=await call(b,'/api/rooms/'+id+'/messages',{body:'Recibido, conversación real',key:'respuesta-bob-0001'},'POST');
  assert.equal(reply.status,201);
  assert.equal((await call(a,'/api/search?q=Recibido')).data.items.length,1);
  assert.equal((await call(e,'/api/search?q=Recibido')).data.items.length,0);
  const group=await call(a,'/api/rooms',{kind:'group',name:'Proyecto real',members:['bob']},'POST');
  assert.equal(group.status,201);
  assert.equal((await call(b,'/api/rooms')).data.items.length,2);
  assert.equal((await call(e,'/api/rooms/'+group.data.roomId+'/messages')).status,404);
  await reader.cancel();
  await service.stop();
  service=await startChat({dbPath,port:0});origin='http://127.0.0.1:'+service.address.port;
  assert.equal((await call(b,'/api/rooms/'+id+'/messages')).data.items.length,2);
  assert.equal((await call(e,'/api/rooms/'+id+'/messages')).status,404);
});
